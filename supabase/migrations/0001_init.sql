-- ---------------------------------------------------------------------
-- Haftalık otomatik sohbet temizliği: 1 haftadır last_message_at
-- güncellenmeyen chats satırlarını (ve cascade ile messages'ı) siler.
-- pg_cron extension'ının Supabase projesinde açık olması gerekir.
-- ---------------------------------------------------------------------
create extension if not exists pg_cron;

select cron.schedule(
  'weekly-inactive-chat-cleanup',
  '0 3 * * 0',
  $$delete from public.chats where last_message_at < now() - interval '7 days'$$
);
